import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { type FormEvent, useState } from 'react';
import { Link } from 'react-router-dom';
import { AuthCard } from '../components/AuthCard';
import { Field } from '../components/Dialog';
import { buttonClass, errorMessage, inputClass } from '../lib/forms';
import { disableMfa, enableMfa, mfaStatus, startMfaSetup } from '../lib/mfa';

/**
 * Your two-step verification with Microsoft Authenticator: scan a QR code, confirm with the
 * first code, and from then on sign-in asks for a code after the password.
 */
export function SecurityPage() {
  const qc = useQueryClient();
  const { data: status, isLoading } = useQuery({ queryKey: ['mfa'], queryFn: mfaStatus });
  const [code, setCode] = useState('');
  const [password, setPassword] = useState('');
  const [done, setDone] = useState<string | null>(null);

  const setup = useMutation({ mutationFn: startMfaSetup });
  const enable = useMutation({
    mutationFn: () => enableMfa(code),
    onSuccess: () => {
      setup.reset();
      setCode('');
      setDone('Two-step verification is on. Next time you sign in, have your phone ready.');
      qc.invalidateQueries({ queryKey: ['mfa'] });
    },
  });
  const disable = useMutation({
    mutationFn: () => disableMfa(password),
    onSuccess: () => {
      setPassword('');
      setDone('Two-step verification is off. Sign-in asks only for your password.');
      qc.invalidateQueries({ queryKey: ['mfa'] });
    },
  });

  const onEnable = (e: FormEvent) => {
    e.preventDefault();
    enable.mutate();
  };
  const onDisable = (e: FormEvent) => {
    e.preventDefault();
    disable.mutate();
  };
  const alert = (error: unknown) =>
    error ? (
      <p role="alert" className="rounded-md bg-red-soft px-3 py-2 text-red">
        {errorMessage(error)}
      </p>
    ) : null;

  return (
    <AuthCard
      title="Two-step verification"
      intro="Sign in with your password and a code from Microsoft Authenticator on your phone."
    >
      <div className="flex flex-col gap-3">
        {done && (
          <p role="status" className="rounded-md bg-green-soft px-3 py-2">
            {done}
          </p>
        )}
        {isLoading && <p className="text-muted">Loading…</p>}

        {status?.enabled && (
          <form onSubmit={onDisable} className="flex flex-col gap-3">
            <p>
              <b>On.</b> Sign-in asks for a code from Microsoft Authenticator.
            </p>
            <p className="text-xs text-muted">
              Moving to a new phone? Turn it off here, then set it up again with the new phone.
            </p>
            <Field label="Your password, to turn it off">
              <input
                type="password"
                autoComplete="current-password"
                className={inputClass}
                value={password}
                required
                onChange={(e) => setPassword(e.target.value)}
              />
            </Field>
            {alert(disable.error)}
            <button type="submit" className={buttonClass()} disabled={disable.isPending}>
              {disable.isPending ? 'Turning off…' : 'Turn off two-step verification'}
            </button>
          </form>
        )}

        {status && !status.enabled && !setup.data && (
          <>
            <p>
              <b>Off.</b> Anyone with your password can sign in as you.
            </p>
            {alert(setup.error)}
            <button
              type="button"
              className={buttonClass('primary')}
              disabled={setup.isPending}
              onClick={() => {
                setDone(null);
                setup.mutate();
              }}
            >
              {setup.isPending ? 'Preparing…' : 'Set up Microsoft Authenticator'}
            </button>
          </>
        )}

        {status && !status.enabled && setup.data && (
          <form onSubmit={onEnable} className="flex flex-col gap-3">
            <ol className="flex list-decimal flex-col gap-1.5 pl-5">
              <li>Install Microsoft Authenticator on your phone (App Store or Google Play).</li>
              <li>
                In the app, tap <b>+</b>, choose <b>Other account</b> and scan this code.
              </li>
            </ol>
            <div
              className="mx-auto w-48 rounded-md border border-line bg-white p-1"
              role="img"
              aria-label="QR code to add SedHub to Microsoft Authenticator"
              // SVG markup generated by the API's QR code library, not user content.
              dangerouslySetInnerHTML={{ __html: setup.data.qrSvg }}
            />
            <p className="text-xs text-muted">
              Can’t scan? Choose <b>Enter code manually</b> in the app, with account{' '}
              <b>{setup.data.account}</b> and key{' '}
              <code data-testid="mfa-secret" className="font-mono font-semibold text-ink">
                {setup.data.secret}
              </code>
              .
            </p>
            <Field label="3. Enter the 6-digit code the app shows">
              <input
                className={`${inputClass} font-mono tracking-[0.3em]`}
                inputMode="numeric"
                autoComplete="one-time-code"
                pattern="[0-9]{6}"
                maxLength={6}
                required
                value={code}
                onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
              />
            </Field>
            {alert(enable.error)}
            <button type="submit" className={buttonClass('primary')} disabled={enable.isPending}>
              {enable.isPending ? 'Checking…' : 'Turn on'}
            </button>
          </form>
        )}

        <Link to="/" className="text-center text-xs text-muted hover:text-ink">
          Back to SedHub
        </Link>
      </div>
    </AuthCard>
  );
}
